"""scripts/release_launcher.py writes a release's assets, and the launcher they hold runs it."""

from __future__ import annotations

import hashlib
import importlib.util
import os
import shutil
import subprocess
import sys
from pathlib import Path
from types import ModuleType

import pytest

pytestmark = pytest.mark.skipif(sys.platform == "win32", reason="the launcher is a POSIX script")

_REPO_ROOT = Path(__file__).resolve().parents[2]
_SCRIPT = _REPO_ROOT / "scripts" / "release_launcher.py"


def _load_script() -> ModuleType:
    # scripts/ is not a package (and is not shipped in the wheel), so load the file by path.
    spec = importlib.util.spec_from_file_location("release_launcher", _SCRIPT)
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


release_launcher = _load_script()

_SH = shutil.which("sh") or "/bin/sh"
_PYTHON = (_REPO_ROOT / ".python-version").read_text(encoding="utf-8").strip()
_TAG = "v0.1.0"
_WHEEL = "pup_finetune-0.1.0-py3-none-any.whl"
_URL = f"https://github.com/DataDog/pup-finetune/releases/download/{_TAG}/{_WHEEL}"
_EXPORT = """\
# This file was autogenerated by uv via the following command:
#    uv export --frozen --no-dev --all-extras --no-emit-project --no-hashes
httpx==0.28.1
    # via pup-finetune
pydantic==2.11.7

rich==14.0.0 ; sys_platform != 'emscripten'
"""


@pytest.mark.parametrize(
    ("tag", "version"),
    [
        ("v1.2.3", "1.2.3"),
        ("v0.1.0-rc.1", "0.1.0rc1"),
        ("v2.0.0-a.2", "2.0.0a2"),
        ("v1.0.0-b3", "1.0.0b3"),
    ],
)
def test_version_of_reads_the_tag_as_hatch_vcs_names_the_wheel(tag: str, version: str) -> None:
    assert release_launcher.version_of(tag) == version


@pytest.mark.parametrize("tag", ["1.2.3", "v1.2", "v1.2.3-beta", "v1.2.3rc1", "v1.2.3-rc.1-x"])
def test_version_of_refuses_other_tags(tag: str) -> None:
    with pytest.raises(release_launcher.ReleaseError, match=r"is not vX\.Y\.Z"):
        release_launcher.version_of(tag)


def test_constraint_lines_keep_only_requirements() -> None:
    assert release_launcher.constraint_lines(_EXPORT) == [
        "httpx==0.28.1",
        "pydantic==2.11.7",
        "rich==14.0.0 ; sys_platform != 'emscripten'",
    ]


@pytest.mark.parametrize(
    ("text", "match"),
    [("# only comments\n", "has no requirements"), ("-e .\nhttpx==0.28.1\n", "has options")],
)
def test_constraint_lines_refuse_what_cannot_constrain(text: str, match: str) -> None:
    with pytest.raises(release_launcher.ReleaseError, match=match):
        release_launcher.constraint_lines(text)


@pytest.mark.parametrize("text", ["", "3", "3.12'; rm -rf ~", "python3.12"])
def test_python_version_refuses_what_uv_cannot_pin(tmp_path: Path, text: str) -> None:
    path = tmp_path / ".python-version"
    path.write_text(text, encoding="utf-8")
    with pytest.raises(release_launcher.ReleaseError, match=r"is not X\.Y"):
        release_launcher.python_version(path)


def _inputs(tmp_path: Path, wheel_bytes: bytes = b"wheel bytes") -> tuple[Path, Path]:
    wheel = tmp_path / "dist" / _WHEEL
    wheel.parent.mkdir()
    wheel.write_bytes(wheel_bytes)
    constraints = tmp_path / "dist" / "constraints.txt"
    constraints.write_text(_EXPORT, encoding="utf-8")
    return wheel, constraints


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def test_write_assets_writes_the_wheel_a_launcher_per_platform_and_checksums(
    tmp_path: Path,
) -> None:
    wheel, constraints = _inputs(tmp_path)
    out = tmp_path / "release"

    assets = release_launcher.write_assets(
        tag=_TAG, wheel=wheel, constraints=constraints, out_dir=out
    )

    names = [path.name for path in assets]
    assert names == [
        _WHEEL,
        "pup-finetune-darwin-aarch64",
        "pup-finetune-darwin-x86_64",
        "pup-finetune-linux-aarch64",
        "pup-finetune-linux-x86_64",
        "checksums.txt",
    ]
    launchers = [out / name for name in names if name.startswith("pup-finetune-")]
    assert len({path.read_text(encoding="utf-8") for path in launchers}) == 1
    assert all(os.access(path, os.X_OK) for path in launchers)
    expected = "".join(f"{_sha256((out / name).read_bytes())}  {name}\n" for name in names[:-1])
    assert (out / "checksums.txt").read_text(encoding="utf-8") == expected


def test_the_launcher_pins_the_release(tmp_path: Path) -> None:
    wheel, constraints = _inputs(tmp_path)
    out = tmp_path / "release"
    release_launcher.write_assets(tag=_TAG, wheel=wheel, constraints=constraints, out_dir=out)

    text = (out / "pup-finetune-linux-x86_64").read_text(encoding="utf-8")

    assert text.startswith("#!/bin/sh\n# SPDX-License-Identifier: Apache-2.0\n")
    assert f"tag='{_TAG}'" in text
    assert f"wheel_sha256='{_sha256(b'wheel bytes')}'" in text
    assert "pydantic==2.11.7\n" in text
    assert "# via" not in text
    assert "@" + "TAG@" not in text
    subprocess.run([_SH, "-n", str(out / "pup-finetune-linux-x86_64")], check=True)  # noqa: S603 - sh, on a file this test wrote


def test_write_assets_refuses_a_wheel_from_another_version(tmp_path: Path) -> None:
    wheel, constraints = _inputs(tmp_path)
    with pytest.raises(release_launcher.ReleaseError, match="needs the wheel"):
        release_launcher.write_assets(
            tag="v0.2.0", wheel=wheel, constraints=constraints, out_dir=tmp_path / "release"
        )


def test_write_assets_refuses_a_directory_that_holds_files(tmp_path: Path) -> None:
    wheel, constraints = _inputs(tmp_path)
    out = tmp_path / "release"
    out.mkdir()
    (out / "stale").write_text("", encoding="utf-8")
    with pytest.raises(release_launcher.ReleaseError, match="is not empty"):
        release_launcher.write_assets(tag=_TAG, wheel=wheel, constraints=constraints, out_dir=out)


def test_main_prints_the_version_and_fails_with_a_message(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    wheel, constraints = _inputs(tmp_path)
    args = ["--wheel", str(wheel), "--constraints", str(constraints)]

    assert release_launcher.main(["--tag", _TAG, *args, "--out-dir", str(tmp_path / "a")]) == 0
    assert capsys.readouterr().out == "0.1.0\n"

    assert release_launcher.main(["--tag", "v9", *args, "--out-dir", str(tmp_path / "b")]) == 1
    assert "is not vX.Y.Z" in capsys.readouterr().err


# The launcher itself, run with stand-ins for curl and uv so nothing reaches the network.

_STUB_CURL = """#!/bin/sh
out=""
url=""
while [ $# -gt 0 ]; do
    case "$1" in
        --output|--proto) [ "$1" = --output ] && out=$2; shift 2 ;;
        -*) shift ;;
        *) url=$1; shift ;;
    esac
done
echo "$url" >>"$STUB_LOG/curl"
[ -z "${STUB_CURL_FAIL:-}" ] || exit 22
cp "$STUB_DOWNLOAD" "$out"
"""

_STUB_UV = """#!/bin/sh
printf '%s\\n' "$@" >"$STUB_LOG/uv"
"""


class _Launcher:
    def __init__(self, tmp_path: Path, wheel_bytes: bytes = b"wheel bytes") -> None:
        wheel, constraints = _inputs(tmp_path, wheel_bytes)
        out = tmp_path / "release"
        release_launcher.write_assets(tag=_TAG, wheel=wheel, constraints=constraints, out_dir=out)
        self.path = out / "pup-finetune-darwin-aarch64"
        self.cache = tmp_path / "xdg-cache"
        self.log = tmp_path / "log"
        self.log.mkdir()
        self.download = tmp_path / "download.whl"
        self.download.write_bytes(wheel_bytes)
        self.bin = tmp_path / "bin"
        self.bin.mkdir()
        for name, text in (("curl", _STUB_CURL), ("uv", _STUB_UV)):
            stub = self.bin / name
            stub.write_text(text, encoding="utf-8")
            stub.chmod(0o755)

    @property
    def release_dir(self) -> Path:
        return self.cache / "pup-finetune" / "0.1.0"

    def run(
        self, *args: str, path: str | None = None, **env: str
    ) -> subprocess.CompletedProcess[str]:
        environ = {
            "HOME": str(self.cache.parent),
            "XDG_CACHE_HOME": str(self.cache),
            "PATH": path if path is not None else f"{self.bin}:/usr/bin:/bin",
            "STUB_LOG": str(self.log),
            "STUB_DOWNLOAD": str(self.download),
            **env,
        }
        return subprocess.run(  # noqa: S603 - sh, on the launcher this test rendered
            [_SH, str(self.path), *args], env=environ, capture_output=True, text=True, check=False
        )

    def curl_calls(self) -> list[str]:
        log = self.log / "curl"
        return log.read_text(encoding="utf-8").splitlines() if log.exists() else []


def test_the_launcher_downloads_the_wheel_once_and_runs_it_pinned(tmp_path: Path) -> None:
    launcher = _Launcher(tmp_path)

    first = launcher.run("doctor", "--provider", "fireworks")
    second = launcher.run("--version")

    assert first.returncode == 0, first.stderr
    assert second.returncode == 0, second.stderr
    assert launcher.curl_calls() == [_URL]
    wheel = launcher.release_dir / _WHEEL
    constraints = launcher.release_dir / "constraints.txt"
    assert wheel.read_bytes() == b"wheel bytes"
    assert constraints.read_text(encoding="utf-8").splitlines() == [
        "httpx==0.28.1",
        "pydantic==2.11.7",
        "rich==14.0.0 ; sys_platform != 'emscripten'",
    ]
    assert (launcher.log / "uv").read_text(encoding="utf-8").splitlines() == [
        "tool",
        "run",
        "--quiet",
        "--python",
        _PYTHON,
        "--constraints",
        str(constraints),
        "--from",
        f"pup-finetune[anthropic,baseten,fireworks] @ file://{wheel}",
        "pup-finetune",
        "--version",
    ]
    assert sorted(path.name for path in launcher.release_dir.iterdir()) == [
        "constraints.txt",
        _WHEEL,
    ]


def test_the_launcher_deletes_a_wheel_that_does_not_match(tmp_path: Path) -> None:
    launcher = _Launcher(tmp_path)
    launcher.download.write_bytes(b"something else")

    result = launcher.run("--version")

    assert result.returncode == 1
    assert "does not match this launcher's SHA-256" in result.stderr
    assert not (launcher.log / "uv").exists()
    assert not (launcher.release_dir / _WHEEL).exists()


def test_the_launcher_reports_a_failed_download(tmp_path: Path) -> None:
    launcher = _Launcher(tmp_path)

    result = launcher.run("--version", STUB_CURL_FAIL="1")

    assert result.returncode == 1
    assert f"could not download {_URL}" in result.stderr
    assert list(launcher.release_dir.iterdir()) == []


@pytest.mark.skipif(
    shutil.which("uv", path="/usr/bin:/bin") is not None, reason="uv is installed system-wide"
)
def test_the_launcher_needs_uv(tmp_path: Path) -> None:
    launcher = _Launcher(tmp_path)
    (launcher.bin / "uv").unlink()

    result = launcher.run("--version")

    assert result.returncode == 127
    assert "uv not found on PATH" in result.stderr
